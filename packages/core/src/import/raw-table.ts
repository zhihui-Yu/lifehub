/**
 * 规整二维表。
 *
 * 架构位置：core 包的「导入」模块，是 CSV / XLSX / PDF 文本三种来源的统一中间表示。
 *
 * 说明：无论上游是分隔符文本、电子表格还是 PDF 文本，抽取层都先把它规整成
 * `{ headers, rows }` 这种与具体格式无关的二维表，下游的映射 / 方向推断 / 去重
 * 只认这一种结构（系统设计 §4.2「两阶段」中的「探查」产物）。
 */

/**
 * 从任意来源抽取的规整二维表。
 */
export interface RawTable {
  /** 表头单元格。 */
  headers: string[];
  /** 数据行（每行是长度相等或较短的字符串数组）。 */
  rows: string[][];
}
